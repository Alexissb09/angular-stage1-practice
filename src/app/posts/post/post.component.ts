import { Component, Input } from '@angular/core';
import { Post } from '../post.model';

@Component({
  selector: 'app-post',
  templateUrl: './post.component.html',
  styleUrl: './post.component.css', // Styles were generated by AI :P
})
export class PostComponent {
  readonly maxChars = 100;

  @Input() post!: Post;
  expanded = false;

  // This is how we do the 'read more / read less' functionality in DMS
  get isLong(): boolean {
    return this.post.content.length > this.maxChars;
  }

  get displayedContent(): string {
    return this.isLong && !this.expanded
      ? this.post.content.slice(0, this.maxChars).trimEnd()
      : this.post.content;
  }

  toggle(e: Event): void {
    e.preventDefault();
    this.expanded = !this.expanded;
  }
}
